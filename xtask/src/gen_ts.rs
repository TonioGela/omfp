//! `cargo xtask gen-ts`: TypeScript types of the UI ↔ daemon protocol, generated from the daemon's JSON Schemas
//! (`omfp_protocol::method_schemas()` and `type_schemas()`, AGT-007) into `ui/packages/protocol/src/generated.ts`.
//!
//! Every schema title and `$defs` entry becomes one exported type named like the Rust type; the method table maps each
//! method name to its params and result types. A schema that accepts anything (an omp-defined result, a
//! `serde_json::Value`) becomes `unknown`, except where [`OVERRIDES`] names a type of `@omfp/core`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, bail};
use serde_json::{Map, Value};

/// The generated file, relative to the repository root.
pub const OUTPUT: &str = "ui/packages/protocol/src/generated.ts";

/// Properties whose schema is open (`#[schemars(with = "serde_json::Value")]`) but whose TypeScript type is known:
/// (type, property, type imported from `@omfp/core`).
const OVERRIDES: &[(&str, &str, &str)] = &[("ThreadSummary", "process", "ProcessState")];

/// Renders the generated file from the method schemas (name → `{params, result}`), the method names in table order,
/// the type schemas (name → schema) and the protocol constants.
pub fn render(
    method_schemas: &Value,
    methods: &[&str],
    type_schemas: &Value,
    protocol_version: u32,
    max_frame_bytes: usize,
) -> anyhow::Result<String> {
    let method_schemas = method_schemas
        .as_object()
        .context("method schemas must be an object")?;
    let mut named = Named::default();
    let mut table = Vec::new();
    for method in methods {
        let entry = method_schemas
            .get(*method)
            .with_context(|| format!("no schemas for method {method}"))?;
        let params = named.root(&entry["params"])?;
        let result = named.root(&entry["result"])?;
        table.push((*method, params, result));
    }
    for (name, schema) in type_schemas
        .as_object()
        .context("type schemas must be an object")?
    {
        let title = named.root(schema)?;
        if title != *name {
            bail!("type schema {name} is titled {title}");
        }
    }

    let mut out = String::from(
        "// Generated by `cargo xtask gen-ts` (`just gen-ts`) from the daemon's JSON Schemas\n\
         // (`omfp_protocol::method_schemas()` and `type_schemas()`). Do not edit: `just test` fails when it is stale.\n\n",
    );
    let imports: Vec<&str> = OVERRIDES.iter().map(|(_, _, ty)| *ty).collect();
    writeln!(
        out,
        "import type {{ {} }} from \"@omfp/core\";\n",
        imports.join(", ")
    )?;
    writeln!(
        out,
        "/** Protocol version announced in `system.hello` (PRT-004). */"
    )?;
    writeln!(out, "export const PROTOCOL_VERSION = {protocol_version};\n")?;
    writeln!(
        out,
        "/** Largest text frame either side may send (PRT-013). */"
    )?;
    writeln!(out, "export const MAX_FRAME_BYTES = {max_frame_bytes};\n")?;

    for (name, schema) in &named.types {
        doc(&mut out, schema, 0)?;
        writeln!(
            out,
            "export type {name} ={};\n",
            spaced(&ts(schema, 0, Some(name))?)
        )?;
    }

    writeln!(
        out,
        "/** Params and result type of every method (PRT-010). */"
    )?;
    writeln!(out, "export interface Methods {{")?;
    for (method, params, result) in &table {
        writeln!(
            out,
            "  \"{method}\": {{ params: {params}; result: {result} }};"
        )?;
    }
    writeln!(out, "}}\n")?;
    writeln!(out, "export type MethodName = keyof Methods;")?;
    writeln!(
        out,
        "export type ParamsOf<M extends MethodName> = Methods[M][\"params\"];"
    )?;
    writeln!(
        out,
        "export type ResultOf<M extends MethodName> = Methods[M][\"result\"];\n"
    )?;
    writeln!(out, "/** Every method name, in table order. */")?;
    writeln!(out, "export const METHODS: readonly MethodName[] = [")?;
    for (method, _, _) in &table {
        writeln!(out, "  \"{method}\",")?;
    }
    writeln!(out, "];")?;
    Ok(out)
}

/// Named schemas collected from root schemas and their `$defs`, sorted by name.
#[derive(Debug, Default)]
struct Named {
    types: BTreeMap<String, Value>,
}

impl Named {
    /// Registers a root schema and its definitions; returns the TypeScript type naming it.
    fn root(&mut self, schema: &Value) -> anyhow::Result<String> {
        if let Some(defs) = schema.get("$defs").and_then(Value::as_object) {
            for (name, body) in defs {
                self.insert(name, body.clone())?;
            }
        }
        if is_open(schema) {
            return Ok("unknown".to_owned());
        }
        let title = schema
            .get("title")
            .and_then(Value::as_str)
            .context("a root schema needs a title")?;
        let mut body = schema.clone();
        if let Some(object) = body.as_object_mut() {
            for key in ["$schema", "$defs", "title"] {
                object.remove(key);
            }
        }
        self.insert(title, body)?;
        Ok(title.to_owned())
    }

    fn insert(&mut self, name: &str, body: Value) -> anyhow::Result<()> {
        match self.types.get(name) {
            Some(existing) if *existing != body => {
                bail!("two different schemas are named {name}")
            }
            Some(_) => Ok(()),
            None => {
                self.types.insert(name.to_owned(), body);
                Ok(())
            }
        }
    }
}

/// Keywords that constrain the shape of a value; a schema without any of them accepts anything.
const SHAPE_KEYWORDS: [&str; 9] = [
    "type",
    "$ref",
    "const",
    "enum",
    "oneOf",
    "anyOf",
    "allOf",
    "properties",
    "items",
];

fn is_open(schema: &Value) -> bool {
    match schema {
        Value::Bool(_) => true,
        Value::Object(object) => SHAPE_KEYWORDS.iter().all(|key| !object.contains_key(*key)),
        _ => false,
    }
}

/// The TypeScript type of `schema`; `owner` names the type whose top-level object this is (for [`OVERRIDES`]).
fn ts(schema: &Value, indent: usize, owner: Option<&str>) -> anyhow::Result<String> {
    if is_open(schema) {
        return Ok("unknown".to_owned());
    }
    let object = schema
        .as_object()
        .context("a schema must be an object or a boolean")?;
    if let Some(reference) = object.get("$ref").and_then(Value::as_str) {
        let name = reference
            .strip_prefix("#/$defs/")
            .with_context(|| format!("unsupported $ref {reference}"))?;
        return Ok(name.to_owned());
    }
    if let Some(value) = object.get("const") {
        return Ok(value.to_string());
    }
    if let Some(values) = object.get("enum").and_then(Value::as_array) {
        let literals: Vec<String> = values.iter().map(Value::to_string).collect();
        return Ok(literals.join(" | "));
    }

    let mut parts = Vec::new();
    if let Some(types) = object.get("type") {
        let types: Vec<&str> = match types {
            Value::String(ty) => vec![ty.as_str()],
            Value::Array(types) => types.iter().filter_map(Value::as_str).collect(),
            _ => bail!("unsupported type {types}"),
        };
        let mut alternatives = Vec::new();
        for ty in types {
            alternatives.push(match ty {
                "string" => "string".to_owned(),
                "integer" | "number" => "number".to_owned(),
                "boolean" => "boolean".to_owned(),
                "null" => "null".to_owned(),
                "array" => array(object, indent)?,
                "object" => object_type(object, indent, owner)?,
                other => bail!("unsupported type {other}"),
            });
        }
        parts.push(join_union(&alternatives));
    } else if object.contains_key("properties") {
        parts.push(object_type(object, indent, owner)?);
    }
    for (keyword, separator) in [("oneOf", "|"), ("anyOf", "|"), ("allOf", "&")] {
        if let Some(variants) = object.get(keyword).and_then(Value::as_array) {
            parts.push(variants_type(variants, separator, indent)?);
        }
    }
    match parts.len() {
        0 => bail!("unsupported schema {schema}"),
        1 => Ok(parts.remove(0)),
        _ => Ok(parts
            .iter()
            .map(|part| format!("({part})"))
            .collect::<Vec<_>>()
            .join(" & ")),
    }
}

fn join_union(alternatives: &[String]) -> String {
    if alternatives.len() == 1 {
        return alternatives[0].clone();
    }
    alternatives
        .iter()
        .map(|alternative| parenthesize(alternative))
        .collect::<Vec<_>>()
        .join(" | ")
}

/// Wraps a union or intersection in parentheses so it can be an operand.
fn parenthesize(ty: &str) -> String {
    if (ty.contains(" | ") || ty.contains(" & ")) && !ty.starts_with('{') {
        format!("({ty})")
    } else {
        ty.to_owned()
    }
}

fn array(object: &Map<String, Value>, indent: usize) -> anyhow::Result<String> {
    let items = object
        .get("items")
        .map_or(Ok("unknown".to_owned()), |items| ts(items, indent, None))?;
    Ok(format!("{}[]", parenthesize(&items)))
}

/// Alternatives on one line when they are short and undocumented, else one per line, each with its description.
fn variants_type(variants: &[Value], separator: &str, indent: usize) -> anyhow::Result<String> {
    let rendered = variants
        .iter()
        .map(|variant| ts(variant, indent + 1, None))
        .collect::<anyhow::Result<Vec<_>>>()?;
    let documented = variants
        .iter()
        .any(|variant| variant.get("description").is_some());
    if !documented && rendered.iter().all(|ty| !ty.contains('\n')) {
        return Ok(rendered
            .iter()
            .map(|ty| parenthesize(ty))
            .collect::<Vec<_>>()
            .join(&format!(" {separator} ")));
    }
    let pad = "  ".repeat(indent + 1);
    let mut out = String::new();
    for (variant, ty) in variants.iter().zip(rendered) {
        out.push('\n');
        doc(&mut out, variant, indent + 1)?;
        write!(out, "{pad}{separator} {ty}")?;
    }
    Ok(out)
}

fn object_type(
    object: &Map<String, Value>,
    indent: usize,
    owner: Option<&str>,
) -> anyhow::Result<String> {
    let properties = object.get("properties").and_then(Value::as_object);
    let additional = object
        .get("additionalProperties")
        .filter(|value| **value != Value::Bool(false));
    let Some(properties) = properties.filter(|properties| !properties.is_empty()) else {
        return Ok(match additional {
            Some(values) => format!("Record<string, {}>", ts(values, indent, None)?),
            None => "Record<string, never>".to_owned(),
        });
    };
    if additional.is_some() {
        bail!("objects with both properties and additionalProperties are not supported");
    }
    let required: Vec<&str> = object
        .get("required")
        .and_then(Value::as_array)
        .map(|required| required.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let pad = "  ".repeat(indent + 1);
    let mut out = String::from("{\n");
    // Sorted: the output must not depend on serde_json's `preserve_order` feature.
    let sorted: BTreeMap<&String, &Value> = properties.iter().collect();
    for (name, schema) in sorted {
        doc(&mut out, schema, indent + 1)?;
        let optional = if required.contains(&name.as_str()) {
            ""
        } else {
            "?"
        };
        let override_ty = OVERRIDES
            .iter()
            .find(|(ty, property, _)| Some(*ty) == owner && property == name)
            .map(|(_, _, ts_type)| (*ts_type).to_owned());
        let ty = match override_ty {
            Some(ty) => ty,
            None => ts(schema, indent + 1, None)?,
        };
        writeln!(
            out,
            "{pad}{}{optional}:{};",
            property_name(name),
            spaced(&ty)
        )?;
    }
    write!(out, "{}}}", "  ".repeat(indent))?;
    Ok(out)
}

/// `ty` after a `=` or `:`: on the same line after a space, or starting on the next line for a multi-line union.
fn spaced(ty: &str) -> String {
    if ty.starts_with('\n') {
        ty.to_owned()
    } else {
        format!(" {ty}")
    }
}

fn property_name(name: &str) -> String {
    let identifier = name.chars().enumerate().all(|(index, c)| {
        c == '_' || c == '$' || c.is_ascii_alphabetic() || (index > 0 && c.is_ascii_digit())
    });
    if identifier && !name.is_empty() {
        name.to_owned()
    } else {
        Value::String(name.to_owned()).to_string()
    }
}

/// The schema's description as a `JSDoc` comment.
fn doc(out: &mut String, schema: &Value, indent: usize) -> std::fmt::Result {
    let Some(description) = schema.get("description").and_then(Value::as_str) else {
        return Ok(());
    };
    let pad = "  ".repeat(indent);
    let description = description.replace("*/", "*\\/");
    let lines: Vec<&str> = description.lines().collect();
    if let [line] = lines.as_slice() {
        return writeln!(out, "{pad}/** {line} */");
    }
    writeln!(out, "{pad}/**")?;
    for line in lines {
        if line.is_empty() {
            writeln!(out, "{pad} *")?;
        } else {
            writeln!(out, "{pad} * {line}")?;
        }
    }
    writeln!(out, "{pad} */")
}

/// The file as generated from this build of `omfp-protocol`.
pub fn generate() -> anyhow::Result<String> {
    render(
        &omfp_protocol::method_schemas(),
        omfp_protocol::METHODS,
        &omfp_protocol::type_schemas(),
        omfp_protocol::PROTOCOL_VERSION,
        omfp_protocol::MAX_FRAME_BYTES,
    )
}

/// Writes [`OUTPUT`] under `root`.
pub fn run(root: &Path) -> anyhow::Result<()> {
    let path = root.join(OUTPUT);
    std::fs::write(&path, generate()?).with_context(|| format!("writing {}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn types(schema: &Value) -> String {
        let mut named = Named::default();
        named.root(schema).expect("valid schema");
        let mut out = String::new();
        for (name, body) in &named.types {
            writeln!(
                out,
                "{name} = {}",
                ts(body, 0, Some(name)).expect("supported")
            )
            .expect("write");
        }
        out
    }

    // spec: AGT-007
    #[test]
    fn objects_map_required_and_optional_properties() {
        let schema = json!({
            "title": "Repo",
            "type": "object",
            "properties": {
                "name": {"type": "string", "description": "Shown in lists."},
                "remoteUrl": {"type": ["string", "null"]},
                "tags": {"type": "array", "items": {"type": "string"}},
                "createdAt": {"type": "integer", "format": "int64"},
                "extra": true
            },
            "required": ["name", "tags", "createdAt"]
        });
        assert_eq!(
            types(&schema),
            "Repo = {\n  createdAt: number;\n  extra?: unknown;\n  /** Shown in lists. */\n  name: string;\n  \
             remoteUrl?: string | null;\n  tags: string[];\n}\n"
        );
    }

    // spec: AGT-007
    #[test]
    fn tagged_enums_become_unions_of_literal_tagged_objects_and_defs_become_named_types() {
        let schema = json!({
            "title": "Event",
            "oneOf": [
                {
                    "type": "object",
                    "properties": {"kind": {"const": "removed", "type": "string"}, "id": {"type": "string"}},
                    "required": ["kind", "id"]
                },
                {"description": "Kept.", "$ref": "#/$defs/Kind"}
            ],
            "$defs": {"Kind": {"enum": ["a", "b"], "type": "string"}}
        });
        assert_eq!(
            types(&schema),
            "Event = \n  | {\n    id: string;\n    kind: \"removed\";\n  }\n  /** Kept. */\n  | Kind\nKind = \"a\" | \"b\"\n"
        );
    }

    // spec: AGT-007
    #[test]
    fn open_and_empty_schemas() {
        let mut named = Named::default();
        assert_eq!(
            named.root(&json!({"title": "AnyValue"})).expect("root"),
            "unknown"
        );
        assert_eq!(
            types(&json!({"title": "Empty", "type": "object"})),
            "Empty = Record<string, never>\n"
        );
        assert_eq!(
            types(&json!({"title": "Ids", "type": "array", "items": {"type": ["string", "null"]}})),
            "Ids = (string | null)[]\n"
        );
    }

    // spec: AGT-007
    #[test]
    fn a_name_used_for_two_different_schemas_is_an_error() {
        let mut named = Named::default();
        named
            .root(&json!({"title": "A", "type": "string"}))
            .expect("first");
        assert!(
            named
                .root(&json!({"title": "A", "type": "integer"}))
                .is_err()
        );
    }

    // spec: AGT-007
    #[test]
    fn the_committed_typescript_protocol_is_up_to_date() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let committed = std::fs::read_to_string(root.join(OUTPUT)).unwrap_or_default();
        let generated = generate().expect("generates");
        assert!(
            committed == generated,
            "{OUTPUT} is stale: run `just gen-ts` and commit the result"
        );
    }
}
